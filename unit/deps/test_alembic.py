"""Dependency contract: alembic (the database migration engine).

Alembic is how Open WebUI builds and evolves its schema. The whole story:

  * **Bootstrap** (`config.py::run_migrations`, called at import when
    ``ENABLE_DB_MIGRATIONS``):
    ``from alembic import command`` /
    ``from alembic.config import Config as AlembicConfig`` ->
    ``cfg = AlembicConfig(OPEN_WEBUI_DIR / 'alembic.ini')`` ->
    ``cfg.set_main_option('script_location', <migrations dir>)`` ->
    ``command.upgrade(cfg, 'head')``.
  * **Runtime env** (`migrations/env.py`): ``import alembic.context`` then
    ``alembic_config = alembic.context.config``;
    ``alembic_config.config_file_name`` / ``.get_main_option(...)`` /
    ``.set_main_option('sqlalchemy.url', ...)`` /
    ``.get_section(alembic_config.config_ini_section, {})``;
    ``alembic.context.configure(url=.., target_metadata=.., literal_binds=..,
    dialect_opts=..)`` (offline) and ``configure(connection=..,
    target_metadata=..)`` (online); ``alembic.context.begin_transaction()``;
    ``alembic.context.run_migrations()``; ``alembic.context.is_offline_mode()``.
  * **Migration scripts** (`migrations/versions/*.py`, `migrations/util.py`):
    ``from alembic import op`` and the schema-edit verbs:
    ``op.get_bind`` / ``create_table`` / ``drop_table`` / ``add_column`` /
    ``drop_column`` / ``create_index`` / ``drop_index`` / ``alter_column`` /
    ``create_primary_key`` / ``create_unique_constraint`` /
    ``drop_constraint`` / ``rename_table`` / ``execute``, plus the SQLite
    workaround ``with op.batch_alter_table(name) as batch_op:`` and on that
    ``batch_op`` the same column/constraint verbs.

A failed migration is a non-starting server, so this module pins exactly that
surface AND drives a real migration end to end against an in-memory SQLite
database (the same ``command.upgrade(cfg, 'head')`` the bootstrap runs), so an
`alembic` bump that removed/renamed/changed any of it fails loudly here instead
of bricking startup.

Pattern mirrors the unit/deps/ exemplar: symbol-existence + signature checks
for the API surface, plus an offline behavioural contract that exercises the
engine against SQLite ``:memory:`` (no network, no external DB). Uses the
`depcheck` fixture from unit/deps/conftest.py.
"""

