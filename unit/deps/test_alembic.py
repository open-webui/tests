# Submodules the backend `from`-imports / imports directly.
USED_SUBMODULES = [
    "alembic.command",  # config.py: from alembic import command
    "alembic.config",  # config.py: from alembic.config import Config
    "alembic.context",  # env.py: import alembic.context
    "alembic.op",  # versions/*.py + util.py: from alembic import op
]

