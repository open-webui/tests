# --------------------------------------------------------------------------- #
# End-to-end: drive a real migration against SQLite :memory: — the exact
# command.upgrade(cfg, 'head') the bootstrap runs, with an op.* migration body.
# --------------------------------------------------------------------------- #
def _write_migration_env(tmp_path: Path) -> Path:
    """Create a minimal but complete alembic migration tree in tmp_path that
    mirrors how the backend wires env.py + a versioned script, then return the
    migrations directory. The migration body uses the same op.* verbs the real
    Open WebUI migrations use (create_table/create_index/add_column/...)."""
    migrations = tmp_path / "migrations"
    versions = migrations / "versions"
    versions.mkdir(parents=True)

    # env.py: online run against the connection alembic is configured with.
    (migrations / "env.py").write_text(
        textwrap.dedent(
            """
            from alembic import context
            from sqlalchemy import engine_from_config, pool

            config = context.config

            def run_migrations_online():
                connectable = engine_from_config(
                    config.get_section(config.config_ini_section, {}),
                    prefix="sqlalchemy.",
                    poolclass=pool.NullPool,
                )
                with connectable.connect() as connection:
                    context.configure(connection=connection, target_metadata=None)
                    with context.begin_transaction():
                        context.run_migrations()

            if context.is_offline_mode():
                # offline path unused by this test
                url = config.get_main_option("sqlalchemy.url")
                context.configure(url=url, literal_binds=True,
                                  dialect_opts={"paramstyle": "named"})
                with context.begin_transaction():
                    context.run_migrations()
            else:
                run_migrations_online()
            """
        ),
        encoding="utf-8",
    )

    # A single revision exercising the real op.* verb surface.
    (versions / "0001_init.py").write_text(
        textwrap.dedent(
            """
            import sqlalchemy as sa
            from alembic import op

            revision = "0001_init"
            down_revision = None
            branch_labels = None
            depends_on = None

            def upgrade():
                # Mirror real migrations: guarded create_table + index + column.
                conn = op.get_bind()
                op.create_table(
                    "widget",
                    sa.Column("id", sa.Text(), primary_key=True),
                    sa.Column("name", sa.Text(), nullable=False),
                    sa.Column("created_at", sa.BigInteger(), nullable=False),
                )
                op.create_index("ix_widget_name", "widget", ["name"])
                op.add_column("widget", sa.Column("note", sa.Text(), nullable=True))
                op.execute("INSERT INTO widget (id, name, created_at) "
                           "VALUES ('w1', 'first', 0)")

            def downgrade():
                op.drop_index("ix_widget_name")
                op.drop_table("widget")
            """
        ),
        encoding="utf-8",
    )
    return migrations


def test_command_upgrade_runs_real_migration_on_sqlite(depcheck, tmp_path):
    """The headline behavioural contract: reproduce config.py's bootstrap end to
    end. Build a Config, point script_location at a generated migrations tree,
    set a SQLite file URL, then ``command.upgrade(cfg, 'head')`` — exactly what
    run_migrations() does. Afterwards the table the migration created (via the
    op.* verbs) must exist and hold the inserted row, and alembic must record
    the applied revision. This proves the whole engine (Config -> command ->
    env.py context.configure/run_migrations -> op.*) works together.
    """
    depcheck.load(IMPORT_NAME)
    command = depcheck.load("alembic.command")
    config_mod = depcheck.load("alembic.config")
    sa = depcheck.load("sqlalchemy")

    migrations = _write_migration_env(tmp_path)
    db_path = tmp_path / "test.db"
    url = f"sqlite:///{db_path.as_posix()}"

    cfg = config_mod.Config()
    cfg.set_main_option("script_location", str(migrations))
    cfg.set_main_option("sqlalchemy.url", url)

    # The exact call the bootstrap makes.
    command.upgrade(cfg, "head")

    engine = sa.create_engine(url)
    try:
        with engine.connect() as conn:
            # Table + data created by the op.* migration body exist.
            rows = conn.execute(sa.text("SELECT id, name, note FROM widget")).fetchall()
            assert rows == [("w1", "first", None)]
            # alembic stamped the applied revision in its version table.
            ver = conn.execute(sa.text("SELECT version_num FROM alembic_version")).scalar()
            assert ver == "0001_init"
    finally:
        engine.dispose()


def test_command_downgrade_reverts_migration_on_sqlite(depcheck, tmp_path):
    """Counterpart: after upgrade to head, ``command.downgrade(cfg, 'base')``
    must run the migration's op.drop_* body and remove the table. Pins that the
    down-path verbs (drop_index/drop_table) execute through the engine too."""
    depcheck.load(IMPORT_NAME)
    command = depcheck.load("alembic.command")
    config_mod = depcheck.load("alembic.config")
    sa = depcheck.load("sqlalchemy")

    migrations = _write_migration_env(tmp_path)
    db_path = tmp_path / "test.db"
    url = f"sqlite:///{db_path.as_posix()}"

    cfg = config_mod.Config()
    cfg.set_main_option("script_location", str(migrations))
    cfg.set_main_option("sqlalchemy.url", url)

    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")

    engine = sa.create_engine(url)
    try:
        with engine.connect() as conn:
            present = conn.execute(
                sa.text("SELECT name FROM sqlite_master WHERE type='table' AND name='widget'")
            ).fetchall()
            assert present == [], "downgrade did not drop the widget table"
    finally:
        engine.dispose()


def test_batch_alter_table_runs_on_sqlite(depcheck, tmp_path):
    """SQLite cannot ALTER many things in place, so the real migrations wrap
    edits in ``with op.batch_alter_table(name) as batch_op:`` (table-copy under
    the hood). Drive a migration whose body uses batch_op.add_column and
    batch_op.drop_column against SQLite and confirm the resulting schema."""
    depcheck.load(IMPORT_NAME)
    command = depcheck.load("alembic.command")
    config_mod = depcheck.load("alembic.config")
    sa = depcheck.load("sqlalchemy")

    migrations = tmp_path / "migrations"
    versions = migrations / "versions"
    versions.mkdir(parents=True)
    (migrations / "env.py").write_text(
        textwrap.dedent(
            """
            from alembic import context
            from sqlalchemy import engine_from_config, pool
            config = context.config
            connectable = engine_from_config(
                config.get_section(config.config_ini_section, {}),
                prefix="sqlalchemy.", poolclass=pool.NullPool,
            )
            with connectable.connect() as connection:
                context.configure(connection=connection, target_metadata=None)
                with context.begin_transaction():
                    context.run_migrations()
            """
        ),
        encoding="utf-8",
    )
    (versions / "0001_batch.py").write_text(
        textwrap.dedent(
            """
            import sqlalchemy as sa
            from alembic import op

            revision = "0001_batch"
            down_revision = None
            branch_labels = None
            depends_on = None

            def upgrade():
                op.create_table(
                    "thing",
                    sa.Column("id", sa.Text(), primary_key=True),
                    sa.Column("old_col", sa.Text(), nullable=True),
                )
                with op.batch_alter_table("thing") as batch_op:
                    batch_op.add_column(sa.Column("new_col", sa.Text(), nullable=True))
                    batch_op.drop_column("old_col")

            def downgrade():
                op.drop_table("thing")
            """
        ),
        encoding="utf-8",
    )

    db_path = tmp_path / "batch.db"
    url = f"sqlite:///{db_path.as_posix()}"
    cfg = config_mod.Config()
    cfg.set_main_option("script_location", str(migrations))
    cfg.set_main_option("sqlalchemy.url", url)

    command.upgrade(cfg, "head")

    engine = sa.create_engine(url)
    try:
        cols = {c["name"] for c in sa.inspect(engine).get_columns("thing")}
        assert "new_col" in cols, "batch_op.add_column did not add new_col"
        assert "old_col" not in cols, "batch_op.drop_column did not drop old_col"
    finally:
        engine.dispose()
