def _identified_conversation() -> list[dict]:
    return [
        {"role": "user", "content": _long("q1 "), "id": "u1"},
        {"role": "assistant", "content": _long("a1 "), "id": "a1"},
        {"role": "user", "content": _long("q2 "), "id": "u2"},
        {"role": "assistant", "content": _long("a2 "), "id": "a2"},
        {"role": "user", "content": _long("q3 "), "id": "u3"},
        {"role": "assistant", "content": _long("a3 "), "id": "a3"},
    ]


def _compact_with_upsert(compaction, chat_utils, monkeypatch, messages, metadata):
    _patch_config(monkeypatch, compaction, _enabled_config())
    upsert = AsyncMock()

    async def fake_generate_chat_completion(request, form_data, user, **_kwargs):
        return _completion("SUMMARY")

    monkeypatch.setattr(chat_utils, "generate_chat_completion", fake_generate_chat_completion)
    monkeypatch.setattr(compaction.Chats, "upsert_message_to_chat_by_id_and_message_id", upsert)
    result = _run(
        compaction.compact_messages_for_request(
            _fake_request(), None, messages, metadata, "direct-model", MODELS
        )
    )
    return result, upsert


def test_checkpoint_is_written_on_the_first_retained_message(
    compaction, chat_utils, monkeypatch
):
    messages = _identified_conversation()
    (result, _summary, compacted), upsert = _compact_with_upsert(
        compaction,
        chat_utils,
        monkeypatch,
        messages,
        {"chat_id": "chat-1", "user_message_id": "u-current"},
    )
    assert compacted is True
    upsert.assert_awaited_once()
    args, kwargs = upsert.await_args
    assert args[0] == "chat-1"
    assert args[1] == result[0]["id"]
    assert args[2] == {"contextSummary": "SUMMARY"}
    assert kwargs.get("touch") is False


def test_temporary_chat_ids_are_not_persisted(compaction, chat_utils, monkeypatch):
    for chat_id in ("temporary:abc", "local:abc", "channel:abc"):
        _result, upsert = _compact_with_upsert(
            compaction,
            chat_utils,
            monkeypatch,
            _identified_conversation(),
            {"chat_id": chat_id, "user_message_id": "u-current"},
        )
        assert upsert.await_count == 0, chat_id


def test_summary_checkpoint_round_trips_to_the_next_turn(compaction, chat_utils, monkeypatch):
    """The retained window must survive re-entry, which is what the bug broke."""
    messages = _identified_conversation()
    (result, summary, _compacted), upsert = _compact_with_upsert(
        compaction,
        chat_utils,
        monkeypatch,
        messages,
        {"chat_id": "chat-1", "user_message_id": "u-current"},
    )
    # Replay from the id production actually persisted, not from the one we wish it used.
    checkpoint_id = upsert.await_args.args[1]
    next_turn = [dict(m) for m in messages]
    for message in next_turn:
        if message["id"] == checkpoint_id:
            message["contextSummary"] = summary
    replayed, replayed_summary = compaction._apply_latest_summary_checkpoint(next_turn)
    assert replayed_summary == summary
    assert [m["id"] for m in replayed] == [m["id"] for m in result]


