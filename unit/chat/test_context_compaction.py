def _patch_config(monkeypatch, compaction, values: dict) -> None:
    """Stub the config store, the only I/O `_load_config`/`_generate_summary` do."""

    async def fake_get_many(*keys, **_kwargs):
        return {key: values.get(key) for key in keys if key in values}

    async def fake_get(key, *_args, **_kwargs):
        return values.get(key)

    monkeypatch.setattr(compaction.Config, "get_many", fake_get_many)
    monkeypatch.setattr(compaction.Config, "get", fake_get)


def _enabled_config(**overrides) -> dict:
    values = {
        "chat.context_compaction.enable": True,
        "chat.context_compaction.token_threshold": 10,
        "chat.context_compaction.prompt_template": "",
    }
    values.update(overrides)
    return values


def _fake_request():
    return SimpleNamespace(state=SimpleNamespace())


def _completion(text: str):
    return {"choices": [{"message": {"content": text}}]}


# A user turn, then a turn whose assistant fans out into three tool results.
# Pre-fix the boundary walks past the tool block and is then clamped back onto
# the last `tool` message, orphaning it from its `tool_calls` assistant.
TOOL_LOOP_MESSAGES = [
    {"role": "user", "content": "first question"},
    {"role": "assistant", "content": "first answer"},
    {"role": "user", "content": "second question"},
    {"role": "assistant", "content": "second answer"},
    {"role": "user", "content": "third question"},
    {"role": "assistant", "content": "", "tool_calls": [{"id": "c1"}, {"id": "c2"}]},
    {"role": "tool", "content": "tool result one"},
    {"role": "tool", "content": "tool result two"},
    {"role": "tool", "content": "tool result three"},
    {"role": "assistant", "content": "third answer"},
]


