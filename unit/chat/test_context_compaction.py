    assert compaction._response_text({"choices": [{"message": {"reasoning_content": "r"}}]}) == "r"
    assert compaction._response_text({"output": [{"content": [{"text": "o"}]}]}) == "o"
    assert compaction._response_text(None) == ""
    assert compaction._response_text("plain") == ""


