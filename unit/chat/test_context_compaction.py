def test_load_config_clamps_and_defaults_retention_percentage(monkeypatch, compaction):
    for raw, expected in ((5, 10), (95, 50), ("garbage", 40), (None, 40)):
        _patch_config(
            monkeypatch,
            compaction,
            _enabled_config(**{"chat.context_compaction.retention_percentage": raw}),
        )
        assert _run(compaction._load_config())["retention_percentage"] == expected


def test_retention_percentage_moves_the_boundary(compaction):
    keep_more = compaction._find_compaction_boundary(list(TOOL_LOOP_MESSAGES), 50)
    keep_less = compaction._find_compaction_boundary(list(TOOL_LOOP_MESSAGES), 10)
    assert keep_more <= keep_less
    assert TOOL_LOOP_MESSAGES[keep_less]["role"] == "user"


