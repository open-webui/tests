"""Regression tests for the 0.11.0 context-compaction fixes.

Five separate bugs in `open_webui/utils/context_compaction.py` (plus one in
`open_webui/utils/response.py`) all made automatic context compaction cut the
conversation in the wrong place or fire at the wrong time:

1. Turn boundaries (#27035, commits 959558f, 17e6496). `_find_compaction_boundary`
   walked the split point forward past `tool` messages and then clamped it with
   `min(split, len(messages) - 2)`, which could pull the boundary back into the
   middle of the turn it had just walked past, so an assistant `tool_calls`
   message and its `tool` result ended up on opposite sides of the summary. The
   fix picks the LAST `user` message index at or before the target instead, and
   takes a clamped `retention_percentage`.

2. Summary model on a direct connection (#26806). `_generate_summary` only ever
   resolved the generic task model, so a configured
   `chat.context_compaction.model` was ignored and the summary was generated by
   the chat's own (possibly direct-connection) model.

3. System prompt through compaction (commits 70549c5, 1568868, 44f4f9d, #26713,
   #26710). The system message was just another list element, so it was folded
   into the summary and dropped from the request. It is now hoisted out and
   re-prepended on every return path.

4. Continuity (#27037, commits 0c23466, f730733). The summary checkpoint was
   written on the CURRENT message id rather than the first RETAINED message, so
   the next turn's `_apply_latest_summary_checkpoint` sliced away the whole
   retained window. The save guard also missed the `temporary:` chat prefix and
   bumped the chat's updated_at.

5. Context size after tool calls (commits df94268, e8f2c12, #27031, #26752,
   #24410). `_exceeds_token_threshold` only recognised `input_tokens`, so Ollama
   (`prompt_eval_count`) and llama.cpp (`prompt_n`) usage blocks were invisible
   and compaction never fired; and `merge_usage` SUMMED `prompt_tokens` across a
   tool loop, so three provider calls reported 3x the real prompt size.

6. Context-usage readout (commit 7a9928ef1, #27362). `get_chat_context_usage` does
   not exist before 0.11.0 at all; it is the backend half of the compaction meter
   the composer shows. Section 5d covers it, so those three tests fail on v0.10.2
   with `AttributeError` rather than a wrong value. That is a capability gap, not a
   behavioural regression, and it is called out here so nobody mistakes it for one.

Discriminates: passes on v0.11.0 and v0.11.1, fails on v0.10.2 (boundary lands on
a `tool` message, the compaction model and the system message are dropped, the
checkpoint is written on the current message id, Ollama/llama.cpp usage is ignored
and `prompt_tokens` is summed across the tool loop).
"""

