def _conversation(turns: int, tools_per_turn: int) -> list[dict]:
    messages: list[dict] = []
    for turn in range(turns):
        messages.append({"role": "user", "content": f"q{turn}"})
        if tools_per_turn:
            messages.append({"role": "assistant", "tool_calls": [{"id": f"c{turn}"}]})
            for tool in range(tools_per_turn):
                messages.append({"role": "tool", "content": f"r{turn}-{tool}"})
        messages.append({"role": "assistant", "content": f"a{turn}"})
    return messages


@pytest.mark.parametrize("turns", [2, 3, 4, 6, 9])
@pytest.mark.parametrize("tools_per_turn", [1, 3])
@pytest.mark.parametrize("retention", [None, 10, 40, 50])
def test_boundary_never_splits_a_turn(compaction, turns, tools_per_turn, retention):
    messages = _conversation(turns, tools_per_turn)
    # `retention is None` drives the default arity, which every ref accepts, so these cases
    # fail on a bad boundary rather than on the signature change.
    boundary = (
        compaction._find_compaction_boundary(messages)
        if retention is None
        else compaction._find_compaction_boundary(messages, retention)
    )
    assert 0 <= boundary < len(messages)
    if boundary:
        assert messages[boundary]["role"] == "user"
    retained = messages[boundary:]
    for idx, message in enumerate(retained):
        if message["role"] == "tool":
            assert any(m.get("tool_calls") for m in retained[:idx])


