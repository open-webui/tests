# 3. System prompt survives compaction (narrow)
# -----------------------------------------------------------------------------


SYSTEM_MESSAGE = {"role": "system", "content": "you are a helpful assistant with rules"}


def _long(text: str) -> str:
    return text * 40


def _compact(compaction, chat_utils, monkeypatch, messages, metadata=None, config=None):
    _patch_config(monkeypatch, compaction, config or _enabled_config())

    async def fake_generate_chat_completion(request, form_data, user, **_kwargs):
        return _completion("SUMMARY")

    monkeypatch.setattr(chat_utils, "generate_chat_completion", fake_generate_chat_completion)
    monkeypatch.setattr(
        compaction.Chats, "upsert_message_to_chat_by_id_and_message_id", AsyncMock()
    )
    return _run(
        compaction.compact_messages_for_request(
            _fake_request(),
            None,
            messages,
            metadata if metadata is not None else {},
            "direct-model",
            MODELS,
        )
    )


def test_system_message_survives_the_compacted_path(compaction, chat_utils, monkeypatch):
    turns = [dict(m, content=_long(m["content"])) for m in _conversation(4, 0)]
    messages = [SYSTEM_MESSAGE, *turns]
    result, summary, compacted = _compact(compaction, chat_utils, monkeypatch, list(messages))
    assert compacted is True
    assert summary == "SUMMARY"
    assert result[0] == SYSTEM_MESSAGE
    assert [m for m in result[1:] if m["role"] == "system"] == []


def test_system_message_survives_a_degenerate_split(compaction, chat_utils, monkeypatch):
    # A single user turn leaves no boundary to split on.
    messages = [
        SYSTEM_MESSAGE,
        {"role": "user", "content": _long("only question ")},
        {"role": "assistant", "content": _long("part one ")},
        {"role": "assistant", "content": _long("part two ")},
        {"role": "assistant", "content": _long("part three ")},
    ]
    result, _summary, compacted = _compact(compaction, chat_utils, monkeypatch, list(messages))
    assert compacted is False
    assert result == messages


def test_compaction_disabled_returns_messages_untouched(compaction, chat_utils, monkeypatch):
    messages = [SYSTEM_MESSAGE, *_conversation(4, 0)]
    result, summary, compacted = _compact(
        compaction,
        chat_utils,
        monkeypatch,
        list(messages),
        config={"chat.context_compaction.enable": False},
    )
    assert (result, summary, compacted) == (messages, None, False)


