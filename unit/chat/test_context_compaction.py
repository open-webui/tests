def _chat(messages_map: dict | None, current_id: str | None):
    history = {"messages": messages_map or {}, "currentId": current_id}
    return SimpleNamespace(id="chat-1", chat={"history": history}, current_message_id=None)


def _linear_map(messages: list[dict]) -> tuple[dict, str]:
    messages_map = {}
    previous_id = None
    for message in messages:
        messages_map[message["id"]] = {**message, "parentId": previous_id, "childrenIds": []}
        if previous_id:
            messages_map[previous_id]["childrenIds"] = [message["id"]]
        previous_id = message["id"]
    return messages_map, previous_id


def test_context_usage_is_none_for_an_empty_chat(compaction, monkeypatch):
    monkeypatch.setattr(compaction.Chats, "get_messages_map_by_chat_id", AsyncMock(return_value={}))
    assert _run(compaction.get_chat_context_usage(_chat({}, None), "direct-model")) is None


def test_context_usage_is_none_when_compaction_is_disabled(compaction, monkeypatch):
    messages_map, current_id = _linear_map(
        [{"id": "m1", "role": "user", "content": "hello"}]
    )
    monkeypatch.setattr(
        compaction.Chats, "get_messages_map_by_chat_id", AsyncMock(return_value=messages_map)
    )
    _patch_config(monkeypatch, compaction, {"chat.context_compaction.enable": False})
    assert _run(compaction.get_chat_context_usage(_chat(messages_map, current_id), None)) is None


def test_context_usage_reports_reported_provider_tokens(compaction, monkeypatch):
    messages_map, current_id = _linear_map(
        [
            {"id": "m1", "role": "user", "content": "hello"},
            {"id": "m2", "role": "assistant", "usage": {"prompt_eval_count": 40_000}},
        ]
    )
    monkeypatch.setattr(
        compaction.Chats, "get_messages_map_by_chat_id", AsyncMock(return_value=messages_map)
    )
    _patch_config(monkeypatch, compaction, _enabled_config(
        **{"chat.context_compaction.token_threshold": 80_000}
    ))
    usage = _run(
        compaction.get_chat_context_usage(_chat(messages_map, current_id), "direct-model")
    )
    assert usage["tokens"] == 40_000
    assert usage["threshold"] == 80_000


