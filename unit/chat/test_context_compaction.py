# -----------------------------------------------------------------------------
# Async driver: keeps every coroutine bounded by an explicit timeout.
# -----------------------------------------------------------------------------


def _run(coroutine, timeout: float = 10.0):
    import asyncio

    async def bounded():
        return await asyncio.wait_for(coroutine, timeout)

    return asyncio.run(bounded())
